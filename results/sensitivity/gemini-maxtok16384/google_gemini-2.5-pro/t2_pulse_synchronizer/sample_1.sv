module pulse_synchronizer #(
    parameter int STAGES = 2
) (
    input  logic clk,
    input  logic rst,
    input  logic toggle_in,
    output logic pulse_out
);

    localparam logic [0:0] ONE_BIT_ZERO = 1'b0;

    logic [STAGES-1:0] sync_chain;
    logic              synced_toggle_d1;
    logic              synced_toggle_d2;

    always_ff @(posedge clk) begin
        if (rst) begin
            sync_chain       <= {STAGES{1'b0}};
            synced_toggle_d1 <= 1'b0;
            synced_toggle_d2 <= 1'b0;
            pulse_out        <= 1'b0;
        end else begin
            // STAGES-deep synchronizer chain for the toggle input.
            if (STAGES > 0) begin
                sync_chain <= {sync_chain[STAGES-2:0], toggle_in};
            end

            // Two-stage pipeline for edge detection.
            // This creates the required STAGES+1 cycle latency.
            if (STAGES > 0) begin
                synced_toggle_d1 <= sync_chain[STAGES-1];
            end else begin
                // If STAGES is 0, toggle_in is considered already synchronized.
                synced_toggle_d1 <= toggle_in;
            end
            synced_toggle_d2 <= synced_toggle_d1;

            // The output pulse is generated by XORing the two delayed versions
            // of the synchronized toggle signal.
            pulse_out <= synced_toggle_d1 ^ synced_toggle_d2;
        end
    end

endmodule
